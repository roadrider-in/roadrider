export type TranslationKey = keyof typeof translations.en;

interface I18nContextType {
  language: LanguageName;
  langCode: LanguageCode;
  setLanguage: (lang: LanguageName) => Promise<void>;
  t: (key: TranslationKey, fallback?: string) => string;
}

const I18nContext = createContext<I18nContextType | null>(null);

const STORAGE_KEY = "roadrider_lang";

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLangState] = useState<LanguageName>("English");

  useEffect(() => {
    let mounted = true;
    AsyncStorage.getItem(STORAGE_KEY).then((stored) => {
      if (!mounted) return;
      if (stored === "हिन्दी" || stored === "Hindi" || stored === "hi") {
        setLangState("हिन्दी");
      }
    }).catch(() => {});
    return () => {
      mounted = false;
    };
  }, []);

  const langCode: LanguageCode = language === "हिन्दी" ? "hi" : "en";

  const setLanguage = async (newLang: LanguageName) => {
    setLangState(newLang);
    try {
      await AsyncStorage.setItem(STORAGE_KEY, newLang);
    } catch (e) {
      console.warn("Could not save language to AsyncStorage:", e);
    }
  };

  const t = (key: TranslationKey, fallback?: string): string => {
    const dict = translations[langCode];
    if (dict && key in dict) {
      return (dict as any)[key];
    }
    const enDict = translations.en;
    if (enDict && key in enDict) {
      return (enDict as any)[key];
    }
    return fallback || key;
  };

  return (
    <I18nContext.Provider value={{ language, langCode, setLanguage, t }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) {
    return {
      language: "English" as LanguageName,
      langCode: "en" as LanguageCode,
      setLanguage: async () => {},
      t: (key: TranslationKey, fallback?: string) => translations.en[key] || fallback || key,
    };
  }
  return ctx;
}
