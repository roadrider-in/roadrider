const REASONS = ["Too many notifications", "Found a better app", "Privacy concerns", "Not using it", "Other"];
/** K8: delete account, four steps then a goodbye screen. */
export function K8_DeleteAccount({ onDeleted }: { onDeleted: () => void }) {
  const nav = useNav();
  const { orders, cancelActiveOrders, profile } = useStore();
  const [step, setStep] = useState(1);
  const [reason, setReason] = useState("");
  const [note, setNote] = useState("");
  const [busy, setBusy] = useState(false);
  const active = orders.filter((o) => o.state === "active").length;
  const blocked = active > 0;
  useEffect(() => { if (step !== 5) return; const t = setTimeout(onDeleted, 4000); return () => clearTimeout(t); }, [step, onDeleted]);
  const back = () => (step > 1 ? setStep(step - 1) : nav.close());
  const remove = async () => {
    setBusy(true);
    if (profile.id) {
      await deleteAccount(profile.id);
    }
    setBusy(false);
    setStep(5);
  };
  if (step === 5) return <main className="state-page" data-screen="K8_Goodbye"><div className="state-icon tone-info"><Icon name="user" size={40}/></div><h1>Your account is deleted</h1><p>Goodbye, {profile.name.split(" ")[0]}. We're sorry to see you go. You're always welcome back.</p><div className="state-actions"><Button onClick={onDeleted}>Back to start</Button></div></main>;
  return <KPage title="Delete account" onBack={back}>
    <div className="step-dots" aria-label={`Step ${step} of 4`}>{[1, 2, 3, 4].map((n) => <i key={n} className={n <= step ? "on" : ""}/>)}<small>Step {step} of 4</small></div>
    {step === 1 && <>
      <div className="warn-hero"><span className="state-icon tone-error small"><Icon name="alert" size={30}/></span><h1>Delete your account?</h1><p>This is permanent and can't be undone. You will lose:</p></div>
      <div className="k-card flush">{[["list", "Order history and receipts"], ["pin", "Saved addresses and payment methods"], ["gift", "Referral coupons and offers"]].map(([i, t]) => <div key={t} className="k-row static"><span className="row-icon danger"><Icon name={i} size={18}/></span><div><strong>{t}</strong></div></div>)}</div>
      {blocked && <div className="banner warning" role="alert"><Icon name="alert" size={18}/><div><strong>Resolve these before deleting</strong>{active > 0 && <p>{active} order{active > 1 ? "s are" : " is"} still active.</p>}</div></div>}
      {active > 0 && <GhostButton onClick={() => { cancelActiveOrders(); nav.toast("Active orders cancelled", "success"); }}>Cancel {active} active order{active > 1 ? "s" : ""}</GhostButton>}
      <Button tone="danger" disabled={blocked} onClick={() => setStep(2)}>Continue</Button>
      <GhostButton onClick={nav.close}>Keep my account</GhostButton>
    </>}
    {step === 2 && <>
      <h1 className="k-title">Why are you leaving?</h1><p className="k-sub">Your feedback helps us improve.</p>
      <div className="chip-row">{REASONS.map((r) => <Chip key={r} on={reason === r} onClick={() => setReason(r)}>{r}</Chip>)}</div>
      <label className="field"><span className="field-label">Tell us more<em>Optional</em></span><textarea value={note} onChange={(e) => setNote(e.target.value)} maxLength={200} rows={4} placeholder="Anything we could have done better?"/></label>
      <Button tone="danger" disabled={!reason} onClick={() => setStep(3)}>Continue</Button>
    </>}
    {step === 3 && <><h1 className="k-title">Confirm it's you</h1><p className="k-sub">Enter the 6-digit code to continue.</p><OtpEntry target={`+91 ${profile.phone}`} cta="Verify & continue" onVerified={() => setStep(4)}/></>}
    {step === 4 && <>
      <div className="warn-hero"><span className="state-icon tone-error small"><Icon name="trash" size={30}/></span><h1>Last step</h1><p>Your profile, orders and rewards will be permanently deleted{reason ? ` (reason: ${reason.toLowerCase()})` : ""}.</p></div>
      <Button tone="danger" onClick={remove} loading={busy}>Delete my account</Button>
      <GhostButton onClick={nav.close}>Keep my account</GhostButton>
    </>}
  </KPage>;
}

